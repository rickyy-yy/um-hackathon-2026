export type TranslationKey = keyof (typeof dict)['ms'];

export function translate(
  key: TranslationKey,
  locale: Locale,
  vars?: Record<string, string | number>
): string {
  const raw = (dict[locale]?.[key] ?? dict.ms[key] ?? key) as string;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] != null ? String(vars[name]) : `{${name}}`
  );
}
